"""
Example of a transfer learning using the ResetNet18 model for image classification, by using
the direct attribute of the model.
Resnet was trainied on ImageNet dataset but in this case it will be transfer learned to classify 
the CIFAR10 dataset. 
"""
import torch.nn as nn
import torchvision.transforms as transforms
from torchvision import models as vmodels


def init_model():
    resnet18_model = vmodels.resnet18(weights='IMAGENET1K_V1')
    return resnet18_model   

def modify_model_for_cifar10(resnet18_model):
    # freeze the trained features of the model by setting the requires_grad to false
    for param in resnet18_model.parameters():
        param.requires_grad = False

    # Modify the classifier head to suit the new task
    original_fc_layer = resnet18_model.fc
    print(f"Original classifier head: {original_fc_layer}")
    in_features = original_fc_layer.in_features
    num_classes = 10
    new_fc_layer = nn.Linear(in_features=in_features, out_features=num_classes)

    # Replace it in the resnet model
    resnet18_model.fc = new_fc_layer
    print(f"Replaced classifer head: {resnet18_model.fc}")


if __name__ == "__main__":
    print("Direct attribute transfer learning on ResNet18 model")
    resnet18_model = init_model()
